import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {wrapReadEvents} from '../events.mjs';
import {wrapReadControllers} from '../controllers.mjs';
import {createReadServices} from '../index.mjs';
import {MobileOrganization} from '../../../backend/organization.mjs';
const id='00000000-0000-0000-0000-000000000001';
test('pin and unpin persist, invalidate cached catalog and reject foreign scope',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'codex-pin-'));t.after(()=>rm(dir,{recursive:true,force:true}));
 const organization=await new MobileOrganization(dir).init();let writes=0;
 const api={get:async path=>{
  if(path==='/api/projects')return{projects:[]};
  if(path==='/api/threads')return{data:[{id,cwd:'/authorized',name:'pin test',createdAt:1,updatedAt:2}]};
  if(path==='/api/organize')return organization.get();
  if(path.startsWith('/api/history?'))return{thread:{id,cwd:'/authorized'},turns:[]};
  throw Error(path);
 },post:async(path,body)=>{assert.equal(path,'/api/organize');writes++;return organization.handle(body);}};
 const services=await createReadServices({api,cacheMs:60000});const task=services['zcode-task'];
 const events=wrapReadEvents(services,{api,autoStart:false});t.after(()=>events.dispose());
 const updates=[];events.channels.project.onDidChange(value=>updates.push(value));
 assert.deepEqual(await task.listPinnedTaskIds(),[]);
 const params={taskId:id,workspacePath:'/authorized',pinned:true};
 const controller=wrapReadControllers(services);t.after(()=>controller.dispose());
 const window=controller.channels['window-controller'];
 assert.equal((await window.mutateTask({address:{taskId:id,workspacePath:'/authorized'},mutation:{kind:'pin',pinned:true}})).pinned,true);
 assert.equal((await window.listTaskList({kind:'pinned',workspaceScopes:[{workspacePath:'/authorized'}]})).items[0].taskId,id);
 assert.deepEqual(await task.listPinnedTaskIds(),[id]);
 assert.equal(updates.length,1);
 assert.equal((await events.channels.project.readTree()).tasks.find(t=>t.taskId===id).pinned,true);
 assert.deepEqual((await new MobileOrganization(dir).init()).get().pins,[id]);
 await assert.rejects(task.setTaskPinned({...params,workspacePath:'/outside'}));
 await assert.rejects(task.setTaskPinned({...params,pinned:'yes'}));
 assert.equal(writes,1);assert.equal(updates.length,1);
 assert.equal((await window.mutateTask({address:{taskId:id,workspacePath:'/authorized'},mutation:{kind:'pin',pinned:false}})).pinned,false);
 assert.equal((await window.listTaskList({kind:'pinned',workspaceScopes:[{workspacePath:'/authorized'}]})).total,0);
 assert.deepEqual(await task.listPinnedTaskIds(),[]);
 assert.deepEqual((await new MobileOrganization(dir).init()).get().pins,[]);assert.equal(updates.length,2);
});
